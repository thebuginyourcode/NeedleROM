#!/usr/bin/env python3
"""
Generates engine/src/main/kotlin/com/needlerom/engine/pokered/EventNames.kt: readable names
for the game's story flags (EVENT_* bits of wEventFlags), per game version.

usage: gen_events.py POKERED_SRC POKEYELLOW_SRC
"""
import os
import re
import sys

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "engine", "src", "main", "kotlin",
                   "com", "needlerom", "engine", "pokered", "EventNames.kt")

WORDS = {"POKEDEX": "Pokédex", "POKEBALLS": "Poké Balls", "POKEBALL": "Poké Ball", "POKEMON": "Pokémon", "HM": "HM",
         "TM": "TM", "SS": "S.S.", "PC": "PC", "OAKS": "Oak's", "OAK": "Oak", "BILLS": "Bill's", "MT": "Mt."}


def nice(name):
    words = []
    for w in name[len("EVENT_"):].split("_"):
        if w in WORDS:
            words.append(WORDS[w])
        elif re.fullmatch(r"\d+(ST|ND|RD|TH)", w):
            words.append(w.lower())
        elif re.fullmatch(r"(TM|HM)\d+", w) or re.fullmatch(r"B?\d+F", w):
            words.append(w)
        else:
            words.append(w.capitalize())
    s = " ".join(words)
    return s[0].upper() + s[1:]


def events(src):
    out, n = {}, 0
    for line in open(os.path.join(src, "constants", "event_constants.asm")):
        line = line.split(";")[0].strip()
        if not line:
            continue
        parts = line.split()
        if parts[0] == "const_def":
            n = 0
        elif parts[0] == "const":
            out[n] = nice(parts[1].rstrip(","))
            n += 1
        elif parts[0] == "const_skip":
            n += int(parts[1]) if len(parts) > 1 else 1
        elif parts[0] == "const_next":
            n = int(parts[1].replace("$", "0x"), 0)
    return out


lines = ["// Generated by tools/gen_events.py. Do not edit.", "package com.needlerom.engine.pokered", "",
         "/** Readable names of the game's story flags (bits of wEventFlags). */", "object EventNames {"]
for key, src in [("RED_BLUE", sys.argv[1]), ("YELLOW", sys.argv[2])]:
    ev = events(src)
    lines.append(f"    val {key}: Map<Int, String> = mapOf(")
    lines += [f'        0x{k:03X} to "{v}",' for k, v in sorted(ev.items())]
    lines.append("    )")
lines.append("}")
open(OUT, "w").write("\n".join(lines) + "\n")
print("wrote", OUT, len(lines))
