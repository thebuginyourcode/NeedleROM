#!/usr/bin/env python3
"""
Assembles engine/asm/needlescript.asm for each game version and writes
engine/src/main/kotlin/com/needlerom/engine/script/ScriptBlobs.kt.

Needs rgbds on PATH and the .sym files of the pret builds (never committed).

usage: build_needlescript.py ROMS_DIR
"""
import os
import subprocess
import sys
import tempfile

ROMS = sys.argv[1]
HERE = os.path.dirname(os.path.abspath(__file__))
ASM = os.path.join(HERE, "..", "engine", "asm", "needlescript.asm")
OUT = os.path.join(HERE, "..", "engine", "src", "main", "kotlin", "com", "needlerom", "engine", "script", "ScriptBlobs.kt")

NEEDED = [
    "hTextID", "wNumSprites", "wMapSpriteData", "wCurMap", "PrintText", "YesNoChoice",
    "wCurrentMenuItem", "GiveItem", "GivePokemon", "wCurOpponent", "wCurEnemyLevel",
    "wTrainerNo", "SaveEndBattleTextPointers", "HealParty", "hMoney", "AddAmountSoldToMoney",
    "IsItemInBag", "hItemToRemoveID", "RemoveItemByID", "PlaySound", "WaitForSoundToFinish", "Bankswitch",
    "DisplayTextID", "wXCoord", "wYCoord", "wStatusFlags5", "wJoyIgnore", "MoveSprite", "wNPCMovementDirections2",
    "hSpriteIndex", "hNPCSpriteOffset", "hNPCPlayerRelativePosPerspective", "hNPCPlayerYDistance", "hNPCPlayerXDistance",
    "wDoNotWaitForButtonPressAfterDisplayingText", "CalcPositionOfPlayerRelativeToNPC", "FindPathToPlayer",
    "wUnusedMapVariable", "wUnusedPlayerDataByte", "wUnusedObtainedBadges", "PlayCry", "PlayMusic", "wLastMusicSoundID",
    "wSpriteStateData2", "hNPCPlayerRelativePosFlags", "wSimulatedJoypadStatesEnd",
    "wSimulatedJoypadStatesIndex", "StartSimulatingJoypadStates",
]
FAR = ["HealParty", "RemoveItemByID", "CalcPositionOfPlayerRelativeToNPC", "FindPathToPlayer"]


def load_sym(path):
    syms = {}
    for line in open(path):
        parts = line.split()
        if len(parts) < 2 or ":" not in parts[0] or line.startswith(";"):
            continue
        b, a = parts[0].split(":")
        syms[parts[1]] = (int(b, 16), int(a, 16))
    return syms


blobs = []
for key, base in [("RED", "pokered"), ("BLUE", "pokeblue"), ("YELLOW", "pokeyellow")]:
    syms = load_sym(os.path.join(ROMS, base + ".sym"))
    with tempfile.TemporaryDirectory() as tmp:
        with open(os.path.join(tmp, "version.inc"), "w") as inc:
            for name in NEEDED:
                bank, addr = syms[name]
                inc.write(f"DEF {name} EQU ${addr:04X}\n")
            for name in FAR:
                inc.write(f"DEF BANK_{name} EQU ${syms[name][0]:02X}\n")
        src = open(ASM).read().replace("BANK(HealParty)", "BANK_HealParty").replace("BANK(RemoveItemByID)", "BANK_RemoveItemByID")
        with open(os.path.join(tmp, "needle.asm"), "w") as f:
            f.write(src)
        subprocess.run(["rgbasm", "-I", tmp, "-o", os.path.join(tmp, "n.o"), os.path.join(tmp, "needle.asm")], check=True)
        subprocess.run(["rgblink", "-n", os.path.join(tmp, "n.sym"), "-o", os.path.join(tmp, "n.gb"), os.path.join(tmp, "n.o")], check=True)
        rom = open(os.path.join(tmp, "n.gb"), "rb").read()
        nsyms = load_sym(os.path.join(tmp, "n.sym"))
        end = nsyms["NeedleRunEnd"][1]
        code = rom[0x4000:0x4000 + (end - 0x4000)]
        assert end < 0x4600, "interpreter overflows into the trigger table"
        blobs.append((key, code))
        print(key, len(code), "bytes")

lines = [
    "// Generated by tools/build_needlescript.py from engine/asm/needlescript.asm. Do not edit.",
    "package com.needlerom.engine.script",
    "",
    "internal object ScriptBlobs {",
    "    /** Engine bank contents from \\$4000, per game version. */",
    "    val CODE: Map<String, String> = mapOf(",
]
for key, code in blobs:
    hexs = code.hex()
    chunks = [hexs[i:i + 100] for i in range(0, len(hexs), 100)]
    lines.append(f'        "{key}" to (')
    for i, c in enumerate(chunks):
        lines.append(f'            "{c}"' + (" +" if i < len(chunks) - 1 else ""))
    lines.append("        ),")
lines.append("    )")
lines.append("}")
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write("\n".join(lines) + "\n")
print("wrote", OUT)
