#!/usr/bin/env python3
"""
Generates engine/src/main/kotlin/com/needlerom/engine/script/Sounds.kt: the sound effects
and music tracks an overworld event can play, with names, per game version.

Inputs (never committed): the .sym files and constants of the pret builds.

usage: gen_sounds.py ROMS_DIR POKERED_SRC POKEYELLOW_SRC
"""
import os
import re
import sys

ROMS, RED_SRC, YELLOW_SRC = sys.argv[1:4]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "engine", "src", "main", "kotlin",
                   "com", "needlerom", "engine", "script", "Sounds.kt")


def load_sym(path):
    syms = {}
    for line in open(path):
        p = line.split()
        if len(p) == 2 and ":" in p[0] and not line.startswith(";"):
            b, a = p[0].split(":")
            syms[p[1]] = (int(b, 16), int(a, 16))
    return syms


def nice(const, prefix):
    words = const[len(prefix):].replace("_", " ").title()
    for a, b in [("Pc", "PC"), ("Ss ", "S.S. "), ("Hp", "HP"), ("Ab", "A/B"), ("Gb ", "GB "), ("Pokemon", "Pokémon"),
                 ("Pokedex", "Pokédex"), ("Pokeflute", "Poké Flute"), ("Ii", "II"), ("Pa", "PA")]:
        words = re.sub(r"\b" + a.strip() + r"\b", b.strip(), words) if a.strip().isalnum() else words.replace(a, b)
    words = re.sub(r"([a-z])(\d)", r"\1 \2", words)
    return {"59": "Slots Stop (unused)", "Pokecenter": "Pokémon Center", "Withdraw Deposit": "Withdraw/Deposit",
            "Get Item 1": "Get Item (jingle)", "Get Item 2": "Get Item (short)"}.get(words, words)


def tables(base, src):
    syms = load_sym(os.path.join(ROMS, base + ".sym"))
    consts = open(os.path.join(src, "constants", "music_constants.asm")).read()
    h1 = syms["SFX_Headers_1"]
    sfx, music = [], []
    for name, label in re.findall(r"music_const (\w+),\s+(\w+)", consts):
        if name.startswith("SFX_"):
            if "CRY" in name or "NOISE" in name or not label.endswith("_1"):
                continue
            if label not in syms or label[:-2] + "_3" not in syms:
                continue  # must exist in both overworld audio banks
            bank, addr = syms[label]
            if bank != h1[0]:
                continue
            sfx.append(((addr - h1[1]) // 3, nice(name, "SFX_")))
        elif name.startswith("MUSIC_") and label in syms:
            bank, addr = syms[label]
            music.append(((addr - 0x4000) // 3, bank, nice(name, "MUSIC_")))
    return sorted(sfx), music


out = ["// Generated by tools/gen_sounds.py. Do not edit.", "package com.needlerom.engine.script", "",
       "/** Sound effects (id, name) and music (id, audio bank, name) that overworld events can play. */",
       "object Sounds {", "    class Table(val effects: List<Pair<Int, String>>, val music: List<Triple<Int, Int, String>>)", ""]
for key, base, src in [("RED_BLUE", "pokered", RED_SRC), ("YELLOW", "pokeyellow", YELLOW_SRC)]:
    sfx, music = tables(base, src)
    out.append(f"    val {key} = Table(")
    out.append("        effects = listOf(")
    out += [f'            {i} to "{n}",' for i, n in sfx]
    out.append("        ),")
    out.append("        music = listOf(")
    out += [f'            Triple({i}, 0x{b:02X}, "{n}"),' for i, b, n in music]
    out.append("        ),")
    out.append("    )")
out.append("}")
open(OUT, "w").write("\n".join(out) + "\n")
print("wrote", OUT)
